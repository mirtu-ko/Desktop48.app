/**
 * SNH48 GROUP 历届年度总选（人气总决选 / 年度青春盛典）最终名次数据。
 * 名次、姓名、团体、票数取自 48archive（https://48archive.top/api/elections/<届数>）的 entries，
 * 新人榜取同响应的 meta.newcomers；团体由 team 字段还原（早期届次无团体前缀，按队伍归属映射）。
 * 头像 sid 优先按 pocket_id 回成员库取（官网 zp_<sid>.jpg 命名），成员库已无记录的老成员沿用官网成员 id。
 * 票数只有部分届次的全部名次公布（第 13 届只公布前 48 名），未公布的记 undefined。
 */

/** 一届总选里的单个名次 */
export interface ElectionMember {
  /** 最终名次（1 起） */
  rank: number
  /** 成员姓名（48archive 口径） */
  name: string
  /** 所属团体（含已解散的 SHY48 / IDFT，保留当年的历史口径） */
  group: string
  /** 官网成员 id：拼头像地址用；成员库已无记录的老成员可能没有 */
  sid?: string
  /** 官方公布的票数（未公布的名次没有此值） */
  votes?: number
}

/** 一届总选 */
export interface Election {
  /** 届数（1 起） */
  ordinal: number
  /** 结果公布年份 */
  year: number
  /** 年度主题 */
  theme: string
  /** 结果公布日期 YYYY-MM-DD */
  date: string
  /** 总选排名，按名次升序 */
  members: ElectionMember[]
  /** 新人榜排名，按名次升序；当届没有新人榜则为空数组 */
  newcomers: ElectionMember[]
}

